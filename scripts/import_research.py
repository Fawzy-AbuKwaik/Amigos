"""Import the six research tables without Excel/third-party dependencies.

Run from any directory: python scripts/import_research.py
Example rows are excluded. Unknown systems fail before data.js is modified;
unresolved test/activity links are retained explicitly and reported as warnings.
The legacy questionnaire and medical collections remain until their UI owners
switch to the reviewed schema documented in docs/DATA_HANDOFF.md.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
NS = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
REL = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"
BEGIN = "  // BEGIN WORKBOOK RESEARCH (generated by scripts/import_research.py)"
END = "  // END WORKBOOK RESEARCH"
SYSTEMS = {
    "Brain and behaviour": ("brain", "BRAIN / MOOD", ["sleep", "mind"]),
    "Eyes": ("eyes", "EYES", []),
    "Lungs": ("lungs", "LUNGS", []),
    "Heart and circulation": ("heart", "HEART", []),
    "Blood and lymph (immune)": ("blood", "BLOOD / IMMUNE", []),
    "Body fluids and kidneys": ("fluids", "FLUIDS / KIDNEYS", ["water", "nutrition"]),
    "Muscle and bone": ("muscle", "MUSCLE / BONE", ["activity"]),
    "Metabolic and endocrine": ("metabolic", "METABOLIC", []),
    "Balance and vestibular": ("balance", "BALANCE", []),
}
HAZARDS = {"Space radiation": "radiation", "Isolation and confinement": "isolation",
           "Distance from Earth": "distance", "Gravity fields": "gravity",
           "Hostile closed environment": "environment"}
ACTIVITIES = {
    "Reading": ("reading", ["calm", "sleep"]),
    "Listening to music": ("music", ["calm", "mood"]),
    "Chess with a crewmate": ("chess", ["connection", "mood"]),
    "Asynchronous family message": ("family-message", ["connection"]),
    "Peer check-in": ("peer-checkin", ["connection"]),
    "Private wellbeing journal": ("journal", ["mood", "calm"]),
    "Space gardening": ("gardening", ["mood"]),
    "Sleep wind-down": ("sleep-winddown", ["sleep", "calm"]),
    "Breathing exercise": ("breathing", ["calm"]),
    "Prescribed aerobic exercise": ("aerobic", ["activity"]),
    "Prescribed resistance exercise": ("resistance", ["activity"]),
    "Gentle approved movement break": ("movement-break", ["activity"]),
}
QUESTION_TAGS = {"sleepHours": "sleep", "sleepQualityAMS": "sleep",
                 "happinessAMS": "mood", "stressAMS": "calm",
                 "physicalExhaustionAMS": "energy", "lonelinessAMS": "connection",
                 "mentalFatigueAMS": "focus"}
LEGACY_TESTS = {"blood pressure": "bp", "heart rate": "hr", "ecg": "ecg",
                "spo2": "spo2", "respiratory rate": "rr", "temperature": "temp",
                "blood glucose": "glucose", "blood glucose (fingerstick)": "glucose",
                "haemoglobin": "hgb", "urine concentration": "urine",
                "body mass": "mass", "grip strength": "grip",
                "visual acuity": "acuity", "visual acuity chart": "acuity",
                "eye ultrasound": "eyeus", "radiation dose": "dose"}


def split(value):
    return [v.strip() for v in str(value or "").split(";") if v.strip()]


def slug(value):
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def optional_number(value):
    if value is None or str(value).strip() == "": return None
    number = float(value)
    if not float('-inf') < number < float('inf'): raise ValueError('Non-finite number')
    return int(number) if number.is_integer() else number


def source_fields(source, sheet, row):
    urls = re.findall(r"https?://[^\s;]+", source or "")
    return {"source": source, "sourceUrls": urls,
            "evidenceStatus": "needs-review" if not urls or re.search(r"search summar|verify|placeholder", source, re.I) else "source-linked",
            "sourceSheet": sheet, "sourceRow": row}


def read_tables(path):
    with zipfile.ZipFile(path) as z:
        strings = []
        if "xl/sharedStrings.xml" in z.namelist():
            strings = ["".join(e.itertext()) for e in ET.fromstring(z.read("xl/sharedStrings.xml"))]
        rels = {r.get("Id"): r.get("Target") for r in ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))}
        tables = {}
        for sheet in ET.fromstring(z.read("xl/workbook.xml")).findall("s:sheets/s:sheet", NS):
            target = rels[sheet.get(REL)]
            target = target.lstrip("/") if target.startswith("/") else "xl/" + target
            rows = []
            for row in ET.fromstring(z.read(target)).findall("s:sheetData/s:row", NS):
                values = {}
                for cell in row:
                    col = re.match(r"[A-Z]+", cell.get("r")).group()
                    v = cell.find("s:v", NS)
                    inline = cell.find("s:is", NS)
                    if cell.get("t") == "s" and v is not None: value = strings[int(v.text)]
                    elif inline is not None: value = "".join(inline.itertext())
                    elif v is not None:
                        value = v.text
                        if cell.get("t") not in ("str", "e", "b"):
                            num = float(value)
                            value = int(num) if num.is_integer() else num
                    else: value = None
                    values[col] = value
                rows.append((int(row.get("r")), values))
            tables[sheet.get("name")] = rows
    return tables


def build(path):
    tables = read_tables(path)
    results, coverage, warnings = {}, {}, []
    specs = [("systems", "1 Body systems", "E"), ("tests", "2 Tests", "L"),
             ("symptoms", "3 Signs and symptoms", "G"),
             ("recommendations", "4 Recommendations", "G"),
             ("activities", "5 Activities", "F"), ("questions", "6 Daily questions", "F")]
    system_ids, test_names, activity_names = {}, {}, {}
    for collection, sheet, source_col in specs:
        records, excluded = [], 0
        for row, cells in tables[sheet]:
            name = cells.get("A")
            if row < 4 or not name: continue
            if collection == "questions" and name == "INTEGRATION NOTES": break
            source = cells.get(source_col) or ""
            if re.match(r'^EXAMPLE\b', str(name), re.I) or re.match(r'^EXAMPLE\b', source, re.I):
                excluded += 1
                continue
            provenance = source_fields(source, sheet, row)
            if provenance['evidenceStatus'] == 'needs-review':
                warnings.append(f'{sheet}!{source_col}{row}: source needs review or a direct link')
            if collection == "systems":
                ident, mark, routine = SYSTEMS.get(name, (slug(name), name.upper(), []))
                hazard_ids = []
                for hazard in split(cells.get("B")):
                    if hazard not in HAZARDS: raise ValueError(f"{sheet}!B{row}: unknown hazard {hazard}")
                    hazard_ids.append(HAZARDS[hazard])
                record = dict(id=ident, name=name, mark=mark, routine=routine,
                              hazards=hazard_ids, explain=cells.get("C"), risks=cells.get("D"), **provenance)
                system_ids[name] = ident
            elif collection == "activities":
                ident, tags = ACTIVITIES.get(name, (slug(name), []))
                minutes = optional_number(cells.get("D"))
                if minutes is not None and (not isinstance(minutes, (int, float)) or minutes <= 0):
                    raise ValueError(f"{sheet}!D{row}: use positive minutes or leave blank")
                kind = cells.get("B")
                if kind not in ("Social", "Mental", "Physical", "Relaxation"):
                    raise ValueError(f"{sheet}!B{row}: unknown activity type {kind}")
                record = dict(id=ident, name=name, type=kind, minutes=minutes,
                              durationBasis="mission-plan" if minutes is None else "configurable-example",
                              goodFor=tags, purpose=split(cells.get("C")), how=cells.get("E"), **provenance)
                activity_names[name] = ident
            elif collection == "questions":
                match = re.match(r"([A-Za-z][A-Za-z0-9]*)\.", str(cells.get("H") or ""))
                if not match:
                    ident = 'question-' + slug(name)
                    kind = str(cells.get('C') or '')
                    options = split(cells.get('D'))
                    scale = re.search(r'Scale\s*(\d+)\s*[-–]\s*(\d+)', kind, re.I)
                    record = dict(id=ident, name=ident, text=name, topic=cells.get('B'),
                                  answerType='integer-scale' if scale else 'boolean' if kind=='Yes/No' else 'multi-choice' if 'tick any' in kind else 'choice' if kind=='Choice' else 'number',
                                  options=options, scaleMin=int(scale[1]) if scale else None,
                                  scaleMax=int(scale[2]) if scale else None, step=1 if scale else None,
                                  direction='as-labeled', interpretation=cells.get('E'),
                                  version='workbook-daily-v1', instrument='team-adapted',
                                  alertThreshold=None, requiresRuleImplementation=bool(cells.get('E')), **provenance)
                    records.append(record)
                    continue
                ident = match.group(1)
                numeric = cells.get("C") == "Number"
                anchors = {int(k): v.strip().rstrip(".") for k, v in re.findall(r"(?:^|;\s*)(0|5|10)\s*=\s*([^;.]+)", cells.get("D") or "")}
                if not numeric and set(anchors) != {0, 5, 10}:
                    raise ValueError(f"{sheet}!D{row}: expected anchors 0, 5 and 10")
                record = dict(id=ident, name=ident, tag=QUESTION_TAGS.get(ident, ident),
                              text=name, topic=cells.get("B"), answerType="number" if numeric else "integer-scale",
                              unit="hours" if numeric else None, scaleMin=None if numeric else 0,
                              scaleMax=None if numeric else 10, step=0.1 if numeric else 1, anchors=anchors,
                              direction="descriptive" if numeric else "higher-more-disturbance",
                              recall=cells.get("G"), interpretation=cells.get("E"),
                              implementationNotes=cells.get("H"), instrument="adapted-sleep-duration" if numeric else "selected-AMS-style",
                              version="amigos-daily-v2", alertThreshold=None, **provenance)
            elif collection == "tests":
                body = cells.get("B")
                if body not in system_ids: raise ValueError(f"{sheet}!B{row}: unknown system {body}")
                ident = LEGACY_TESTS.get(name.lower(), slug(name))
                lo, hi = optional_number(cells.get("D")), optional_number(cells.get("E"))
                if any(x is not None and not isinstance(x, (int, float)) for x in [lo, hi]):
                    raise ValueError(f"{sheet}!D{row}: reference limits must be numbers or blank")
                if lo is not None and hi is not None and lo > hi: raise ValueError("Reversed reference range: " + name)
                record = dict(id=ident, name=name, system=system_ids[body], unit=cells.get("C"),
                              referenceLow=lo, referenceHigh=hi, rangeAppliesTo=cells.get("F"),
                              why=cells.get("G"), steps=split(cells.get("H")), availableIn=split(cells.get("I")),
                              frequency=cells.get("J"), inputType=cells.get("K"), **provenance)
                test_names[name.lower()] = ident
            elif collection == "symptoms":
                body = cells.get("B")
                if body not in system_ids: raise ValueError(f"{sheet}!B{row}: unknown system {body}")
                linked_tests, unresolved = [], []
                for test in split(cells.get("D")):
                    ident = test_names.get(test.lower())
                    if not ident:
                        alias = {'eye ultrasound':'ocular ultrasound', 'visual acuity chart':'visual acuity',
                                 'ecg':'heart electrical activity (ecg)', 'spo2':'blood oxygen saturation (spo2)',
                                 'temperature':'body temperature'}.get(test.lower(),test.lower())
                        ident = test_names.get(alias)
                    if not ident:
                        unresolved.append(test)
                        warnings.append(f'{sheet}!D{row}: unresolved test {test}')
                    else: linked_tests.append(ident)
                urgency = {"Self-care": "self", "Run tests": "tests", "Contact surgeon now": "now"}.get(cells.get("C"))
                if not urgency: raise ValueError(f"{sheet}!C{row}: unknown urgency")
                hazards = split(cells.get("F"))
                if any(h not in HAZARDS for h in hazards): raise ValueError(f"{sheet}!F{row}: unknown hazard")
                record = dict(id=slug(name), name=name, system=system_ids[body], urgency=urgency,
                              tests=linked_tests, unresolvedTestNames=unresolved, becomesUrgentWhen=cells.get("E"),
                              hazards=[HAZARDS[h] for h in hazards], **provenance)
            else:
                # Human-written triggers remain text. The importer never invents executable clinical rules.
                record = dict(id=slug(name), triggerText=name, usesDataFrom=split(cells.get("B")),
                              action=cells.get("C"), mentalApproach=cells.get("D"),
                              activityNames=split(cells.get("E")), escalation=cells.get("F"),
                              rule=None, requiresRuleImplementation=True, **provenance)
            records.append(record)
        ids = [r["id"] for r in records]
        if len(ids) != len(set(ids)): raise ValueError("Duplicate IDs in " + sheet)
        results[collection] = records
        coverage[collection] = dict(imported=len(records), excludedExamples=excluded,
                                    status="imported" if records else "awaiting-reviewed-rows")
    for record in results["recommendations"]:
        record["activityIds"] = []
        record['unresolvedActivityNames'] = []
        for name in record.pop("activityNames"):
            alias = {'Journaling':'Private wellbeing journal',
                     'Family message':'Asynchronous family message',
                     'Crew conversation':'Peer check-in', 'Gardening':'Space gardening',
                     'Listen to music':'Listening to music', 'Message or call family':'Asynchronous family message',
                     'Resistance exercise session':'Prescribed resistance exercise',
                     'Treadmill or cycle session':'Prescribed aerobic exercise'}.get(name,name)
            if alias not in activity_names:
                record['unresolvedActivityNames'].append(name)
                warnings.append(f'Recommendation {record["id"]}: unresolved activity {name}')
            else: record["activityIds"].append(activity_names[alias])
    if not results["systems"] or not results["activities"] or not results["questions"]:
        raise ValueError("Expected reviewed systems, activities and daily questions")
    results["meta"] = dict(schemaVersion=2, workbook="docs/amigos-data-request.xlsx",
                           sha256=hashlib.sha256(path.read_bytes()).hexdigest(), coverage=coverage,
                           matchingBasis="Activity tags are preference categories, not validated clinical triggers.",
                           warnings=warnings,
                           questionnaireIntegration="Use dailyQuestions with each item's answerType and scale metadata; legacy questions are retained for the existing UI.")
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workbook", type=Path, default=ROOT / "docs/amigos-data-request.xlsx")
    parser.add_argument("--check", action="store_true", help="Validate and report counts without writing")
    args = parser.parse_args()
    research = build(args.workbook)
    if not args.check:
        path = ROOT / "js/data.js"
        text = path.read_text(encoding="utf-8")
        block = BEGIN + "\n  const research = " + json.dumps(research, ensure_ascii=False, indent=2) + ";\n"
        block += """  data.research = research;
  data.systems = research.systems;
  data.activities = research.activities;
  data.dailyQuestions = research.questions;
  // Legacy medical collections and 1-5 questions are still used by the current UI.
  // Their owners migrate against research.tests/symptoms/recommendations and dailyQuestions.
  data.legacyQuestionnaire = { version: 'amigos-routine-v1', scaleMin: 1, scaleMax: 5 };
""" + END
        if BEGIN in text:
            text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, count=1, flags=re.S)
        else:
            anchor = "  // Active crew member, shared by every view."
            if anchor not in text: raise ValueError("data.js integration anchor not found")
            text = text.replace(anchor, block + "\n\n" + anchor, 1)
        text = text.replace("// All content the interface reads: hazards, body systems, tests, symptoms,\n// activities, daily questions and crew. The values below are PLACEHOLDERS until\n// the research tables arrive. docs/amigos-data-request.xlsx has the same\n// structure, sheet by sheet, so the real data can replace this file's contents\n// without touching the interface code.",
            "// Shared data and crew selection. Reviewed workbook data is applied below.\n// Inspect AMIGOS.data.research.meta.coverage for imported and pending tables.\n// Legacy medical/demo content remains until its UI owner completes migration.")
        path.write_text(text, encoding="utf-8")
    print(json.dumps(research["meta"]["coverage"], indent=2))


if __name__ == "__main__":
    main()
